function placeholderPhoto(id: string, label: string, hue: number) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="600" viewBox="0 0 800 600">
    <defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0%" stop-color="hsl(${hue} 45% 62%)"/>
      <stop offset="100%" stop-color="hsl(${(hue + 40) % 360} 40% 32%)"/>
    </linearGradient></defs>
    <rect width="800" height="600" fill="url(#g)"/>
    <text x="400" y="310" font-family="sans-serif" font-size="44" fill="rgba(255,255,255,.92)" text-anchor="middle">${label}</text>
  </svg>`;

  return {
    id,
    downloadUrl: `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`,
    width: 800,
    height: 600,
  };
}

